const PART_BY_ID = new Map(PARTS.map((part) => [part.id, part]));

export function getPart(id: string | null | undefined): MoonPart | null {
  if (!id) return null;
  return PART_BY_ID.get(id) ?? null;
}

export function partsForSlot(slot: PartSlot): MoonPart[] {
  return PARTS.filter((part) => part.slot === slot);
}

export function slotInfo(slot: PartSlot): SlotInfo {
  return SLOTS.find((item) => item.id === slot) ?? SLOTS[0];
}

