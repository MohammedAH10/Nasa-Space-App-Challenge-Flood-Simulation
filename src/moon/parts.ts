export function buildName(build: RocketBuild): string {
  const name = build.name.trim();
  return name.length > 0 ? name : "My Moon Rocket";
}

export function partCountBySlot(build: RocketBuild): Record<PartSlot, number> {
  const counts = {
    nose: 0,
    capsule: 0,
    fuel: 0,
    engine: 0,
    booster: 0,
    fins: 0,
    legs: 0,
  };
  for (const slot of SLOTS) {
    if (getPart(build.parts[slot.id])) counts[slot.id] += 1;
  }
  return counts;
}
